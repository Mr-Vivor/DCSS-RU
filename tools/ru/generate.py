"""Generate game names and a wiki term index from one reviewed-form registry.

Standard-library only. Unknown/unfinished messages keep the engine's English fallback.
"""
from pathlib import Path
from collections import Counter
import argparse
import json
import re
from catalog import STATIC_FILES, DESCRIPTION_FILES, DATABASE_FILES, read_db, write_db, reviewed_descriptions, reviewed_random_messages, artifact_power_fields
from message_catalog import coverage as message_coverage

ROOT = Path(__file__).resolve().parents[2]
CASES = ("nom", "gen", "dat", "acc", "ins", "prep")


def page_slug(key):
    # Colons create alternate data streams on Windows, rather than wiki pages.
    return re.sub(r'-+', '-', re.sub(r'[<>:"/\\|?*\x00-\x20]+', '-', key.lower())).strip('-. ')


def load_entities():
    entities = json.loads((ROOT / "localization/ru/entities.json").read_text(encoding="utf8"))
    ids, names = set(), set()
    for entity in entities:
        if entity["id"] in ids or entity["en"] in names:
            raise ValueError("Duplicate entity: " + entity["id"])
        ids.add(entity["id"])
        names.add(entity["en"])
        for number in ("singular", "plural"):
            for case in CASES:
                value = entity["forms"][number][case]
                if not value or any(c in value for c in ("@", "{", "}", "\n")):
                    raise ValueError("Invalid grammatical form: " + entity["id"])
        counted_few = entity["forms"].get("counted_few")
        if counted_few is not None and (not counted_few or any(c in counted_few for c in ("@", "{", "}", "\n"))):
            raise ValueError("Invalid counted form: " + entity["id"])
    return entities


def game_entries(entities):
    entries = {}

    def add(key, value):
        if key in entries and entries[key] != value:
            raise ValueError("Conflicting generated key: " + key)
        entries[key] = value

    for entity in entities:
        en, plural = entity["en"], entity["en_plural"]
        singular_forms, plural_forms = entity["forms"]["singular"], entity["forms"]["plural"]
        gender = "{" + entity["gender"] + "}"
        for prefix in ("", "the ", "a ", "an ", "your "):
            key = prefix + en
            add(key, gender + singular_forms["nom"])
            for case in CASES:
                add("{" + case + "}" + key, gender + singular_forms[case])
            add(key + "'s", gender + singular_forms["gen"])
        # English fish/deer-style invariant plurals must not overwrite the
        # singular key. Counted phrases still receive all Russian forms below.
        for prefix in (("", "the ", "your ") if plural != en else ()):
            add(prefix + plural, "{pl}" + plural_forms["nom"])
            for case in CASES:
                add("{" + case + "}" + prefix + plural, "{pl}" + plural_forms[case])
        counted = "@num@ " + plural
        add(counted, "@num@ " + plural_forms["gen"])
        for category, value in (("one", singular_forms["nom"]),
                                ("few", entity["forms"].get("counted_few", singular_forms["gen"])),
                                ("many", plural_forms["gen"])):
            add("{" + category + "}" + counted, "@num@ " + value)
        # Oblique cases use the singular only for counts ending in one.
        for case in ("gen", "dat", "ins", "prep"):
            for category in ("one", "few", "many"):
                value = (singular_forms if category == "one" else plural_forms)[case]
                add("{" + case + "_" + category + "}" + counted, "@num@ " + value)
        for category in ("one", "few", "many"):
            if category == "one":
                value = singular_forms["acc"]
            elif entity["animate"]:
                value = plural_forms["gen"]
            else:
                value = singular_forms["gen"] if category == "few" else plural_forms["gen"]
            add("{acc_" + category + "}" + counted, "@num@ " + value)
    return entries


def serialize_db(entries):
    lines = ["# Generated by tools/ru/generate.py; edit localization/ru/entities.json.", ""]
    for key, value in sorted(entries.items()):
        lines.extend(("%%%%", key, value))
    return "\n".join(lines) + "\n"


def outputs(entities):
    def quoted(value):
        return '"' + value + '"' if value != value.strip() else value

    result = {ROOT / "crawl-ref/source/dat/translate/ru/entities.txt": serialize_db(game_entries(entities))}
    terms = json.loads((ROOT / "localization/ru/terms.json").read_text(encoding="utf8"))
    term_entries = {}
    for category, group in terms.items():
        for english, russian in group.items():
            term_entries[english] = russian
            term_entries["the " + english] = russian if category == "gods" else russian.lower()
            term_entries["a " + english] = russian if category == "gods" else russian.lower()
    result[ROOT / "crawl-ref/source/dat/translate/ru/terms.txt"] = serialize_db(term_entries)
    system_messages = json.loads((ROOT / "localization/ru/system-messages.json").read_text(encoding="utf8"))
    result[ROOT / "crawl-ref/source/dat/translate/ru/system.txt"] = write_db(
        {quoted(k): quoted(v) for k, v in system_messages.items()},
        "Generated from localization/ru/system-messages.json.")
    static = json.loads((ROOT / "localization/ru/static.json").read_text(encoding="utf8"))
    static_entries = {}
    for filename in STATIC_FILES:
        expected = read_db(ROOT / f"crawl-ref/source/dat/translate/{filename}.txt", True)
        missing = set(expected) - set(static[filename])
        if missing:
            raise ValueError(f"Missing static translations in {filename}: {sorted(missing)}")
        static_entries.update(static[filename])
    # The original hand-edited translations and morphological registry win.
    reserved = set(term_entries) | set(game_entries(entities)) | set(system_messages)
    for path in (ROOT / "crawl-ref/source/dat/translate/ru").glob("*.txt"):
        if path.name not in ("entities.txt", "terms.txt", "static.txt", "system.txt"):
            reserved.update(read_db(path, True))
    static_entries = {key: value for key, value in static_entries.items() if key not in reserved}
    messages_coverage = message_coverage(reserved | set(static_entries))
    result[ROOT / "localization/ru/message-coverage.json"] = json.dumps(messages_coverage, ensure_ascii=False, indent=2) + "\n"
    result[ROOT / "crawl-ref/source/dat/translate/ru/static.txt"] = write_db(
        {quoted(k): quoted(v) for k, v in static_entries.items()},
        "Generated from localization/ru/static.json; draft prose, protected engine tokens.")
    random_messages = reviewed_random_messages()
    for filename, entries in random_messages.items():
        result[ROOT / f"crawl-ref/source/dat/database/ru/{filename}.txt"] = write_db(
            {key: entry["text"] for key, entry in entries.items()},
            "Generated from localization/ru/random-messages.json; reviewed random-message variants.")
    result[ROOT / "wiki/ru/static-catalog.json"] = json.dumps(static, ensure_ascii=False, indent=2) + "\n"
    descriptions = json.loads((ROOT / "localization/ru/character-descriptions.json").read_text(encoding="utf8"))
    gods = read_db(ROOT / "crawl-ref/source/dat/descript/ru/gods.txt")
    gods.update(json.loads((ROOT / "localization/ru/god-introductions.json").read_text(encoding="utf8")))
    descriptions["gods"] = gods
    for filename, group in descriptions.items():
        source = read_db(ROOT / f"crawl-ref/source/dat/descript/{filename}.txt")
        if set(source) != set(group):
            raise ValueError("Character descriptions do not match upstream: " + filename)
        result[ROOT / f"crawl-ref/source/dat/descript/ru/{filename}.txt"] = write_db(group,
            "Generated from localization/ru/character-descriptions.json.")
    for category, filename in (("species", "species"), ("background", "backgrounds"), ("gods", "gods")):
        group = descriptions.get(filename) or read_db(ROOT / f"crawl-ref/source/dat/descript/ru/{filename}.txt")
        for english, title in terms[category].items():
            slug = english.lower().replace(" ", "-")
            page = [f"# {title}", "", f"**English:** {english}", "", group[english], ""]
            if category == "gods":
                for suffix, heading in ((" powers", "Силы и благочестие"), (" wrath", "Гнев"), (" extra", "Дополнительно")):
                    if english + suffix in group:
                        page.extend(("## " + heading, "", group[english + suffix], ""))
            page.extend(("Текст и название взяты из тех же словарей, что использует игра. Черновик для вычитки.", ""))
            result[ROOT / "wiki/ru/characters" / category / (slug + ".md")] = "\n".join(page)
    result[ROOT / "wiki/ru/terms.json"] = json.dumps(terms, ensure_ascii=False, indent=2) + "\n"
    reviewed = reviewed_descriptions()
    item_names = {e["en"]: e["forms"]["singular"]["nom"] for e in entities if e["kind"] == "item"}
    item_names.update(terms.get("items", {}))
    reference_names = {
        "items": item_names,
        "skills": terms["skill"],
        "spells": {name + " spell": title for name, title in terms["spell"].items()},
        "ability": {name + " ability": title for name, title in terms["ability"].items()},
        "cards": terms.get("cards", {}),
        "unrand": terms.get("unrand", {}),
        "monsters": {e["en"]: e["forms"]["singular"]["nom"] for e in entities if e["kind"] == "monster"},
    }
    reference_headings = {"items": "Предметы", "skills": "Навыки",
                          "spells": "Заклинания", "ability": "Способности", "monsters": "Монстры", "cards": "Карты", "unrand": "Уникальные артефакты"}
    reference = {}
    reference_index = ["# Справочник предметов, навыков и способностей", "",
                       "Названия и описания синхронизированы с русской версией игры.", ""]
    artifact_powers = {}
    for field in artifact_power_fields():
        powers = artifact_powers.setdefault(field["name"].lower(), [])
        for line in field["text"].splitlines():
            label, separator, text = line.partition(":")
            if separator:
                title = system_messages["{unrand-prop}" + label.strip()].removeprefix("{unrand-prop}")
                description = system_messages[text.strip()]
            else:
                title, description = "", system_messages[line.strip()]
            powers.append(dict(label=title, text=description, source_field=field["field"]))
    for filename, group in reviewed.items():
        source = read_db(ROOT / f"crawl-ref/source/dat/descript/{filename}.txt")
        target_path = ROOT / f"crawl-ref/source/dat/descript/ru/{filename}.txt"
        previous = read_db(target_path) if target_path.exists() else {}
        merged = {k: v for k, v in previous.items() if k in source}
        merged.update({k: entry["text"] for k, entry in group.items()})
        result[target_path] = write_db(merged,
            "Reviewed entries generated from localization/ru/descriptions.json; remaining entries await review.")
        reference[filename] = {}
        if filename in reference_headings:
            reference_index.extend(("## " + reference_headings[filename], ""))
        for key, entry in group.items():
            title = reference_names.get(filename, {}).get(key)
            reference[filename][key] = dict(title=title, text=entry["text"], source_sha256=entry["source_sha256"])
            if not title:
                continue  # Shared description fragments and ego lookup keys are not item names.
            slug = page_slug(key)
            body = entry.get("wiki_text", entry["text"])
            if filename == "unrand":
                power_key = key.lower()
                if entry["text"].startswith("<") and entry["text"].endswith(">"):
                    power_key = entry["text"][1:-1].lower()
                powers = artifact_powers.get(power_key, [])
                reference[filename][key]["powers"] = powers
                if powers:
                    body += "\n\n## Особые свойства\n\n" + "\n".join(
                        "- " + ("**" + power["label"] + ":** " if power["label"] else "") + power["text"]
                        for power in powers)
            result[ROOT / "wiki/ru/reference" / filename / (slug + ".md")] = (
                f"# {title[:1].upper() + title[1:]}\n\n**English:** {key}\n\n{body}\n\n"
                "Название и описание берутся из общих словарей игры и вики.\n")
            reference_index.append(f"- [{title[:1].upper() + title[1:]}]({filename}/{slug}.md)")
        reference_index.append("")
    result[ROOT / "wiki/ru/reference/descriptions.json"] = json.dumps(reference, ensure_ascii=False, indent=2) + "\n"
    result[ROOT / "wiki/ru/reference/README.md"] = "\n".join(reference_index).rstrip() + "\n"
    wiki = {entity["id"]: dict(title=entity["forms"]["singular"]["nom"].capitalize(),
                                en=entity["en"], en_plural=entity["en_plural"],
                                kind=entity["kind"], forms=entity["forms"], review=entity["review"])
            for entity in entities}
    result[ROOT / "wiki/ru/entities.json"] = json.dumps(wiki, ensure_ascii=False, indent=2) + "\n"
    index = ["# Словарь русской вики DCSS", "", "Автоматически создан из общего словаря игры и вики.",
             "", "[Виды, предыстории, боги и навыки](character-terms.md): названия и описания из игры.",
             "[Справочник предметов и навыков](reference/README.md): проверенные описания текущей версии.",
             "Формы со статусом draft допускают точечные исправления.", "", "| ID | Название | English | Статус |",
             "|---|---|---|---|"]
    for entity in entities:
        title = wiki[entity["id"]]["title"]
        index.append(f"| `{entity['id']}` | [{title}](pages/{entity['id']}.md) | {entity['en']} | {entity['review']} |")
        page = [f"# {title}", "", f"**English:** {entity['en']}", f"**ID:** `{entity['id']}`", ""]
        content_path = ROOT / "wiki/ru/content" / (entity["id"] + ".md")
        reviewed_entry = reviewed.get("items" if entity["kind"] == "item" else "monsters", {}).get(entity["en"])
        if reviewed_entry:
            page.extend(("## Описание в игре", "", reviewed_entry["text"], ""))
        if content_path.exists():
            if reviewed_entry:
                page.extend(("## Дополнительно", ""))
            page.extend((content_path.read_text(encoding="utf8").strip(), "", "## Формы названия", ""))
        elif reviewed_entry:
            page.extend(("## Формы названия", ""))
        else:
            page.extend(("Черновая карточка термина. Описание механик и советы ещё не добавлены.", ""))
        page.extend(("| Падеж | Единственное число | Множественное число |", "|---|---|---|"))
        labels = ("Именительный", "Родительный", "Дательный", "Винительный", "Творительный", "Предложный")
        for label, case in zip(labels, CASES):
            page.append(f"| {label} | {entity['forms']['singular'][case]} | {entity['forms']['plural'][case]} |")
        page.extend(("", "Название и формы берутся из `localization/ru/entities.json`. Исправления вносятся туда.", ""))
        result[ROOT / "wiki/ru/pages" / (entity["id"] + ".md")] = "\n".join(page)
    result[ROOT / "wiki/ru/README.md"] = "\n".join(index) + "\n"
    term_index = ["# Виды, предыстории, боги и навыки", "", "Имена из localization/ru/terms.json используются и в игре, и в вики.", ""]
    for category, values in terms.items():
        term_index.extend(("## " + category, "", "| English | Русское название |", "|---|---|"))
        for en, ru in values.items():
            slug = en.lower().replace(" ", "-")
            label = f"[{ru}](characters/{category}/{slug}.md)" if category in ("species", "background", "gods") else ru
            term_index.append(f"| {en} | {label} |")
        term_index.append("")
    result[ROOT / "wiki/ru/character-terms.md"] = "\n".join(term_index)
    stats = dict(entities=len(entities), kinds=dict(Counter(e["kind"] for e in entities)),
                 generated_game_keys=len(game_entries(entities)), review=dict(Counter(e["review"] for e in entities)),
                 wiki_articles=sum((ROOT / "wiki/ru/content" / (e["id"] + ".md")).exists() for e in entities),
                 additional_terms={group: len(values) for group, values in terms.items()},
                 static_catalogs={name: len(static[name]) for name in STATIC_FILES},
                 static_unique_keys=len(set().union(*(set(static[n]) for n in STATIC_FILES))),
                 additional_system_messages=len(system_messages),
                 reviewed_random_messages={name: dict(entries=len(entries),
                     variants=sum(len(e["text"].split("\n\n")) for e in entries.values()))
                     for name, entries in random_messages.items()},
                 imported_message_templates={k: messages_coverage[k] for k in ("total", "translated", "missing")},
                 reviewed_descriptions={name: len(group) for name, group in reviewed.items()},
                 descriptions={name: len(descriptions.get(name) or read_db(ROOT / f"crawl-ref/source/dat/descript/ru/{name}.txt")) for name in DESCRIPTION_FILES},
                 help_databases={name: len(read_db(ROOT / f"crawl-ref/source/dat/database/ru/{name}.txt")) for name in DATABASE_FILES})
    result[ROOT / "localization/ru/coverage.json"] = json.dumps(stats, ensure_ascii=False, indent=2) + "\n"
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated files are stale")
    args = parser.parse_args()
    entities = load_entities()
    stale = []
    for path, content in outputs(entities).items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf8", newline="\n")
    if stale:
        raise SystemExit("Regenerate with python tools/ru/generate.py:\n" + "\n".join(stale))
    print(f"{'Checked' if args.check else 'Generated'} {len(entities)} shared game/wiki entities")


if __name__ == "__main__":
    main()
